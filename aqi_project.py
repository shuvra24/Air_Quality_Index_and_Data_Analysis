# Function to predict AQI and AQI Category from user input
def predict_aqi_and_category():
    print("Enter pollutant values:")
    co = float(input("CO (ppm): "))
    so2 = float(input("SO2 (ppb): "))
    no2 = float(input("NO2 (ppb): "))
    o3 = float(input("O3 (ppb): "))
    pm25 = float(input("PM2.5 (µg/m³): "))
    pm10 = float(input("PM10 (µg/m³): "))

    # Create input as a DataFrame with feature names
    input_data = pd.DataFrame([[co, so2, no2, o3, pm25, pm10]],
                              columns=['CO', 'SO2', 'NO2', 'O3', 'PM2.5', 'PM10'])

    # Scale the input
    input_scaled = scaler.transform(input_data)

    # Predict AQI and AQI Category for each model
    dt_aqi_pred = dt_reg.predict(input_scaled)[0]
    dt_category_pred = dt_clf.predict(input_scaled)[0]
    rf_aqi_pred = rf_reg.predict(input_scaled)[0]
    rf_category_pred = rf_clf.predict(input_scaled)[0]
    mlp_aqi_pred = mlp_reg.predict(input_scaled)[0]
    mlp_category_pred = mlp_clf.predict(input_scaled)[0]

    # Print results
    print("\nPredictions:")
    print("Decision Tree:")
    print(f"  Predicted AQI: {dt_aqi_pred:.2f}")
    print(f"  Predicted AQI Category: {dt_category_pred}")
    print("Random Forest:")
    print(f"  Predicted AQI: {rf_aqi_pred:.2f}")
    print(f"  Predicted AQI Category: {rf_category_pred}")
    print("Multilayer Perceptron:")
    print(f"  Predicted AQI: {mlp_aqi_pred:.2f}")
    print(f"  Predicted AQI Category: {mlp_category_pred}\n")

