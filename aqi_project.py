# Load the dataset
data = pd.read_csv('AQIFinalDataset.csv')

# Features and targets
X = data[['CO', 'SO2', 'NO2', 'O3', 'PM2.5', 'PM10']]
y_aqi = data['AQI']
y_category = data['AQI Category']

# Split the data
X_train, X_test, y_aqi_train, y_aqi_test, y_category_train, y_category_test = train_test_split(
    X, y_aqi, y_category, test_size=0.2, random_state=15
)

# Scale the features
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Train Decision Tree models
dt_reg = DecisionTreeRegressor(max_depth=5, random_state=15)
dt_reg.fit(X_train_scaled, y_aqi_train)
dt_clf = DecisionTreeClassifier(max_depth=5, random_state=15)
dt_clf.fit(X_train_scaled, y_category_train)

# Train Random Forest models
rf_reg = RandomForestRegressor(n_estimators=100, max_depth=5, random_state=15)
rf_reg.fit(X_train_scaled, y_aqi_train)
rf_clf = RandomForestClassifier(n_estimators=100, max_depth=5, random_state=15)
rf_clf.fit(X_train_scaled, y_category_train)

# Train MLP models
mlp_reg = MLPRegressor(hidden_layer_sizes=(100, 50), max_iter=2000, random_state=15)
mlp_reg.fit(X_train_scaled, y_aqi_train)
mlp_clf = MLPClassifier(hidden_layer_sizes=(100, 50), max_iter=2000, random_state=15)
